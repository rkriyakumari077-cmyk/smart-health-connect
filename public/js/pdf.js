// Makes PDF files with the jsPDF library (loaded from /jspdf/jspdf.umd.min.js).
// jsPDF writes text at x, y positions measured in millimetres on an A4 page.

function pdfHeader(pdf, title) {
  pdf.setFillColor(3, 24, 27); // dark header bar
  pdf.rect(0, 0, 210, 25, 'F');
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(16);
  pdf.text('Smart Health Connect', 15, 12);
  pdf.setFontSize(10);
  pdf.text(title, 15, 19);
  pdf.setTextColor(0, 0, 0);
}

function pdfFooter(pdf) {
  pdf.setFontSize(8);
  pdf.setTextColor(100, 100, 100);
  pdf.text('Generated by Smart Health Connect. Please consult your doctor about any questions.', 15, 285);
}

// appointment = one item from /api/appointments (with its prescription)
function downloadPrescription(appointment) {
  const { jsPDF } = window.jspdf;
  const pdf = new jsPDF();
  const p = appointment.prescription;

  pdfHeader(pdf, 'Prescription');
  pdf.setFontSize(11);
  pdf.text('Patient: ' + appointment.patientName, 15, 38);
  pdf.text('Doctor: ' + appointment.doctorName + ' (' + appointment.specialization + ')', 15, 45);
  pdf.text('Date: ' + formatDate(appointment.date), 15, 52);

  pdf.setFontSize(13);
  pdf.text('Diagnosis', 15, 66);
  pdf.setFontSize(11);
  pdf.text(p.diagnosis, 15, 73);

  pdf.setFontSize(13);
  pdf.text('Medicines', 15, 87);
  pdf.setFontSize(11);
  let y = 94;
  p.medicines.forEach((medicine, index) => {
    pdf.text(index + 1 + '. ' + medicine, 15, y);
    y = y + 7;
  });

  if (p.advice) {
    pdf.setFontSize(13);
    pdf.text('Advice', 15, y + 7);
    pdf.setFontSize(11);
    pdf.text(pdf.splitTextToSize(p.advice, 180), 15, y + 14);
  }

  pdfFooter(pdf);
  pdf.save('prescription-' + appointment.date + '.pdf');
}

// booking = one item from /api/test-bookings (with its test and report)
function downloadReport(booking) {
  const { jsPDF } = window.jspdf;
  const pdf = new jsPDF();
  const report = booking.report;

  pdfHeader(pdf, 'Lab Test Report');
  pdf.setFontSize(11);
  pdf.text('Patient: ' + booking.patientName, 15, 38);
  pdf.text('Test: ' + booking.test.name, 15, 45);
  pdf.text('Sample date: ' + formatDate(booking.date) + '    Report date: ' + formatDate(report.date), 15, 52);

  // Table header
  let y = 66;
  pdf.setFontSize(10);
  pdf.setFillColor(242, 248, 247);
  pdf.rect(15, y - 5, 180, 8, 'F');
  pdf.text('Parameter', 17, y);
  pdf.text('Result', 80, y);
  pdf.text('Normal range', 115, y);
  pdf.text('Flag', 165, y);

  // One row for each result. Results outside the range are red.
  for (const r of report.results) {
    y = y + 9;
    pdf.setTextColor(0, 0, 0);
    pdf.text(r.name, 17, y);
    if (r.flag !== 'Normal') pdf.setTextColor(200, 50, 20);
    pdf.text(r.value + ' ' + r.unit, 80, y);
    pdf.setTextColor(0, 0, 0);
    pdf.text(r.range + ' ' + r.unit, 115, y);
    if (r.flag !== 'Normal') pdf.setTextColor(200, 50, 20);
    pdf.text(r.flag, 165, y);
  }

  pdf.setTextColor(0, 0, 0);
  pdf.setFontSize(13);
  pdf.text('Remarks', 15, y + 16);
  pdf.setFontSize(11);
  pdf.text(pdf.splitTextToSize(report.remarks, 180), 15, y + 23);

  pdfFooter(pdf);
  pdf.save('report-' + booking.test.name.split(' ')[0] + '.pdf');
}
